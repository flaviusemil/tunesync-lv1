/*
 * TuneSync C API: the TuneSync runtime (MIDI in -> the key and scale of every unlocked
 * Waves Tune RT) embedded in a C or C++ host, which supplies the mixer.
 *
 * SPDX-License-Identifier: MIT OR Apache-2.0
 *
 * Threads
 *   - The TsMixer callbacks are called ONLY from the runtime's own worker thread
 *     ("tunesync-worker"), one call at a time, never from a thread that calls a ts_*
 *     function and never from one of the host's threads. They may start before ts_start
 *     returns (the first scan) and never happen once ts_stop has returned.
 *   - Every ts_* function may be called from any thread and returns without waiting on a
 *     callback (they only queue work for the worker), except ts_stop.
 *   - ts_stop must not race other calls on the same handle (like free()), and must not be
 *     called from inside a callback (it returns TS_ERR_IN_CALLBACK and does nothing). It
 *     waits for a callback in flight: do not call it while holding a lock the callbacks take.
 *   - Callbacks must not throw (C++): mark them noexcept.
 *
 * Text is UTF-8. Strings TuneSync returns (char *) are the caller's: free each with
 * ts_string_free. Functions returning int give TS_OK (0) or a negative TS_ERR_*.
 * Pointers passed in need only be valid for the call (ts_start copies the TsMixer).
 * No Rust panic crosses this interface: a panic becomes TS_ERR_PANIC or NULL.
 */

